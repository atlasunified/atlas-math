def _is_prime(n: int) -> bool:
    if n < 2:
        return False
    if n == 2:
        return True
    if n % 2 == 0:
        return False
    d = 3
    while d * d <= n:
        if n % d == 0:
            return False
        d += 2
    return True

def _build_problem(rng: random.Random, difficulty: str):
    n = rng.randint(10, 60)
    count = sum(1 for k in range(2, n + 1) if _is_prime(k))
    metadata = {"upper_bound": n, "counting_function_style": "pi(n)"}
    return f"How many prime numbers are less than or equal to {n}?", str(count), metadata
